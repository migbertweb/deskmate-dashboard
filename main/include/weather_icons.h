typedef enum {
    XBM_SUN = 0,            /* 01d — cielo despejado día */
    XBM_MOON,               /* 01n — cielo despejado noche */
    XBM_CLOUD_SUN,          /* 02d — parcialmente nublado día */
    XBM_CLOUD_MOON,         /* 02n — parcialmente nublado noche */
    XBM_CLOUD,              /* 03d/n — nubes dispersas */
    XBM_CLOUDS,             /* 04d/n — muy nublado */
    XBM_RAIN0,              /* 09d/n — lluvia ligera */
    XBM_RAIN1_SUN,          /* 10d — lluvia moderada día */
    XBM_RAIN1_MOON,         /* 10n — lluvia moderada noche */
    XBM_RAIN_LIGHTNING,     /* 11d/n — tormenta */
    XBM_SNOW,               /* 13d/n — nieve */
    XBM_WIND,               /* 50d/n — niebla / viento */
    XBM_ICON_COUNT
} xbm_icon_t;

