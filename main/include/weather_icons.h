/* Mapear código OWM (ej: "04d") a xbm_icon_t */
static inline xbm_icon_t xbm_icon_from_code(const char *code)
{
    if (!code || strlen(code) < 3) return XBM_CLOUD;

    switch (code[0]) {
        case '0':
            switch (code[1]) {
                case '1': return (code[2] == 'd') ? XBM_SUN : XBM_MOON;
                case '2': return (code[2] == 'd') ? XBM_CLOUD_SUN : XBM_CLOUD_MOON;
                case '3': return XBM_CLOUD;
                case '4': return XBM_CLOUDS;
                case '9': return XBM_RAIN0;
                default: break;
            }
            break;
        case '1':
            if (code[1] == '0') return (code[2] == 'd') ? XBM_RAIN1_SUN : XBM_RAIN1_MOON;
            if (code[1] == '1') return XBM_RAIN_LIGHTNING;
            if (code[1] == '3') return XBM_SNOW;
            break;
        case '5':
            if (code[1] == '0') return XBM_WIND;
            break;
    }
    return XBM_CLOUD;
}

