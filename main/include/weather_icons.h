/*
 * weather_icons.h — Iconos de clima 32×32 en formato XBM
 *
 * Formato XBM (X BitMap):
 *   - Cada fila tiene (ancho + 7) / 8 bytes = 4 bytes para 32px
 *   - MSB del primer byte = píxel más a la izquierda de la fila
 *   - bit = 1 → píxel encendido (se dibuja con el color activo)
 *   - bit = 0 → transparente (fondo negro visible)
 *
 * 22 iconos extraídos de proyecto open-source de iconos de clima.
 *
 * Mapeo OWM:
 *   01d → XBM_SUN             01n → XBM_MOON
 *   02d → XBM_CLOUD_SUN       02n → XBM_CLOUD_MOON
 *   03d/n → XBM_CLOUD         04d/n → XBM_CLOUDS
 *   09d/n → XBM_RAIN0         10d → XBM_RAIN1_SUN
 *   10n → XBM_RAIN1_MOON      11d/n → XBM_RAIN_LIGHTNING
 *   13d/n → XBM_SNOW          50d/n → XBM_WIND
 */

